import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { profileOf } from '@make-it-accessible/pipeline/html/profile'
import { parsePage } from '@make-it-accessible/pipeline/model/schema'
import { parseExtraction } from '@make-it-accessible/pipeline/pdf/types'
import { validatePage } from '@make-it-accessible/pipeline/validate/validate'
import { fontLibrary } from './brand.ts'
import { BriefFile } from './look.ts'
import { ROOT } from './paths.ts'
import { loadSources } from './sources.ts'
import { extractWhole } from './wholewords.ts'
import {
  columnsPerPage,
  dietaryCodes,
  fontTally,
  listShapes,
  pricePlacement,
  titleScale,
  type Page,
} from './wiki-facts.ts'

// pnpm wiki: one generated page per document under docs/wiki/documents/ from its saved run and PDF, plus the index.
// A "## Notes" section written by hand in a document page survives regeneration.
const WIKI = join(ROOT, 'docs', 'wiki')
const sources = await loadSources()
const library = await fontLibrary()
await mkdir(join(WIKI, 'documents'), { recursive: true })

const notesOf = async (file: string): Promise<string> => {
  const old = await readFile(file, 'utf8').catch(() => '')
  const at = old.indexOf('\n## Notes')
  return at >= 0 ? old.slice(at).trimEnd() + '\n' : '\n## Notes\n\n(none yet)\n'
}

const rows: string[] = []
for (const s of sources) {
  const pages: Page[] = []
  const findings = { errors: 0, review: 0 }
  for (const d of (await readdir(s.run)).filter((d) => /^p\d+$/.test(d)).sort()) {
    const extraction = parseExtraction(await readFile(join(s.run, d, 'extraction.json'), 'utf8'))
    const fresh = await extractWhole(join(ROOT, s.pdf), extraction.pdfPage)
    extraction.hidden = fresh.hidden
    extraction.lost = fresh.lost
    extraction.runs.forEach((r, i) => {
      const f = fresh.runs[i]
      if (f?.font) r.font = f.font
      if (f?.color) r.color = f.color
      if (f) Object.assign(r, { str: f.str, box: f.box, restored: f.restored, styled: f.styled })
    })
    const structure = parsePage(await readFile(join(s.run, d, 'structure.json'), 'utf8'))
    const v = validatePage(structure, extraction)
    findings.errors += v.errors.length
    findings.review += v.review.length
    pages.push({ structure, extraction })
  }
  const profile = profileOf(pages)
  const briefRaw = await readFile(join(s.run, 'brief.json'), 'utf8').catch(() => null)
  const brief = briefRaw === null ? null : BriefFile.parse(JSON.parse(briefRaw)).brief
  const columns = columnsPerPage(pages)
  const prices = pricePlacement(pages)
  const title = titleScale(pages, profile)
  const codes = dietaryCodes(pages)
  const shapes = listShapes(pages)
  const fonts = fontTally(pages, profile, library).slice(0, 8)
  const file = join(WIKI, 'documents', `${s.slug}.md`)
  const body = `# ${s.title}

Group: ${s.group} · pages: ${String(pages.length)} · type (brief): ${brief?.type ?? 'none'} · generated by \`pnpm wiki\`.

## Layout
- Columns of lists per page: ${columns.join(', ')}
- Price placement: ${String(prices.inline)} inline after the name, ${String(prices.right)} at the column's right
- Lists one dish per line: ${String(shapes.wide)} of ${String(shapes.lists)} (${String(shapes.runOn)} with the description on the name's line)
- Inline brand colours: ${profile?.inks.length ? profile.inks.join(', ') : 'none'}
- Body text ${String(title.body)} pt; largest text ${String(title.largest)} pt (${title.body ? (title.largest / title.body).toFixed(1) : '?'}×): "${title.words}"
- Heading signatures: ${String(profile?.signatures.length ?? 0)}${profile ? ` (${profile.signatures.map((h) => `${h.face.key} ${String(h.size)}pt`).join(', ')})` : ''}
- Dietary legend entries: ${String(codes.legendEntries)}; coded lines "(V, GF)": ${String(codes.codedLines)}
- Brief details: ${brief?.details?.length ? brief.details.map((d) => `${d.kind} near "${d.near}"`).join('; ') : 'none'}

## Fonts (printed → stand-in)
| Family | Characters | Roles | Stand-in |
|---|---|---|---|
${fonts.map((f) => `| ${f.family} | ${String(f.chars)} | ${f.roles} | ${f.standIn ?? '—'} |`).join('\n')}

## Validator
errors ${String(findings.errors)}, review ${String(findings.review)}
${await notesOf(file)}`
  await writeFile(file, body)
  rows.push(
    `| [${s.title}](documents/${s.slug}.md) | ${s.group} | ${columns.join('/')} | ${String(prices.inline)}/${String(prices.right)} | ${title.body ? (title.largest / title.body).toFixed(1) : '?'}× | ${String(fonts.filter((f) => f.standIn).length)}/${String(fonts.length)} | ${String(findings.errors)}/${String(findings.review)} |`,
  )
}
const patterns = (await readdir(join(WIKI, 'patterns')).catch(() => [])).filter((f) => f.endsWith('.md')).sort()
await writeFile(
  join(WIKI, 'index.md'),
  `# Layout wiki

Measured facts per document (generated by \`pnpm wiki\` from the saved runs and PDFs listed in \`validation/private/wiki-sources.json\`) and the patterns we render them by. Read the index and the relevant patterns before planning a layout change; count on the whole set, never on one page.

## Documents
| Document | Group | Columns of lists per page | Prices inline/right | Largest text ÷ body | Fonts with a stand-in | Validator errors/review |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## Patterns
${patterns.map((p) => `- [${p.replace(/\.md$/, '').replace(/-/g, ' ')}](patterns/${p})`).join('\n')}
`,
)
console.info(`${String(sources.length)} documents written to docs/wiki`)
